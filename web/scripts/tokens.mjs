// Generates src/tokens.css (CSS variables) from pump/design/tokens.json, and the
// install files public/manifest.webmanifest and public/icon.svg (colours resolved
// from the same tokens).  Build time only.  Usage: node scripts/tokens.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, "..");
const repoRoot = path.resolve(webRoot, "..");
const src = path.join(repoRoot, "pump", "design", "tokens.json");
const out = path.join(webRoot, "src", "tokens.css");

const tokens = JSON.parse(readFileSync(src, "utf8"));

/** Resolve "{other-name}" aliases recursively. */
function resolver(list) {
  const byName = new Map(list.map((t) => [t.name, t.value]));
  const resolve = (value, seen = new Set()) => {
    const m = /^\{([^}]+)\}$/.exec(String(value).trim());
    if (!m) return String(value);
    const name = m[1];
    if (seen.has(name)) throw new Error(`token alias cycle at ${name}`);
    if (!byName.has(name)) throw new Error(`unknown token alias ${name}`);
    seen.add(name);
    return resolve(byName.get(name), seen);
  };
  return resolve;
}

const lines = [];
const add = (name, value) => lines.push(`  --${name}: ${value};`);

const colorResolve = resolver(tokens.color.tokens);
for (const t of tokens.color.tokens) add(t.name, colorResolve(t.value));

for (const group of ["spacing", "radius", "canvas"]) {
  const list = tokens[group]?.tokens ?? [];
  const resolve = resolver(list);
  for (const t of list) add(t.name, resolve(t.value));
}

const families = tokens.type?.families ?? {};
for (const [name, value] of Object.entries(families)) add(`font-${name}`, value);

for (const g of tokens.type?.groups ?? []) {
  for (const s of g.styles ?? []) {
    add(`fs-${s.name}`, s.fontSize);
    if (s.fontWeight !== undefined) add(`fw-${s.name}`, s.fontWeight);
  }
}

const css =
  "/* Generated by scripts/tokens.mjs from pump/design/tokens.json. Do not edit. */\n" +
  `:root {\n${lines.join("\n")}\n}\n`;

mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, css);
console.log(`tokens.css: ${lines.length} variables`);

// ---- installable app files (public/ is copied into dist/ by Vite) ----------------
const color = (name) => {
  const t = tokens.color.tokens.find((x) => x.name === name);
  if (!t) throw new Error(`unknown colour token ${name}`);
  return colorResolve(t.value);
};
const bg = color("title-bg");
const fg = color("title-text");
const publicDir = path.join(webRoot, "public");
mkdirSync(publicDir, { recursive: true });

// A pump impeller: ring, four curved vanes and a hub, on the title bar colour.
const vane = (angle) =>
  `<path d="M256 256 C300 236 340 190 330 120" transform="rotate(${angle} 256 256)" fill="none" stroke="${fg}" stroke-width="22" stroke-linecap="round"/>`;
const icon =
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">\n` +
  `<rect width="512" height="512" fill="${bg}"/>\n` +
  `<circle cx="256" cy="256" r="170" fill="none" stroke="${fg}" stroke-width="22"/>\n` +
  [0, 90, 180, 270].map(vane).join("\n") +
  `\n<circle cx="256" cy="256" r="30" fill="${fg}"/>\n</svg>\n`;
writeFileSync(path.join(publicDir, "icon.svg"), icon);

const webmanifest = {
  name: "PumpFlow",
  short_name: "PumpFlow",
  description: "API 610 pump test witness workbench, offline in the browser.",
  start_url: ".",
  scope: ".",
  display: "standalone",
  theme_color: bg,
  background_color: color("window-bg"),
  icons: [{ src: "icon.svg", sizes: "any", type: "image/svg+xml", purpose: "any maskable" }],
};
writeFileSync(path.join(publicDir, "manifest.webmanifest"), JSON.stringify(webmanifest, null, 2) + "\n");
console.log("manifest.webmanifest, icon.svg");
