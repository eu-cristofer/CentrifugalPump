// Generates src/tokens.css (CSS variables) from pump/design/tokens.json.
// Build time only.  Usage: node scripts/tokens.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, "..");
const repoRoot = path.resolve(webRoot, "..");
const src = path.join(repoRoot, "pump", "design", "tokens.json");
const out = path.join(webRoot, "src", "tokens.css");

const tokens = JSON.parse(readFileSync(src, "utf8"));

/** Resolve "{other-name}" aliases recursively. */
function resolver(list) {
  const byName = new Map(list.map((t) => [t.name, t.value]));
  const resolve = (value, seen = new Set()) => {
    const m = /^\{([^}]+)\}$/.exec(String(value).trim());
    if (!m) return String(value);
    const name = m[1];
    if (seen.has(name)) throw new Error(`token alias cycle at ${name}`);
    if (!byName.has(name)) throw new Error(`unknown token alias ${name}`);
    seen.add(name);
    return resolve(byName.get(name), seen);
  };
  return resolve;
}

const lines = [];
const add = (name, value) => lines.push(`  --${name}: ${value};`);

const colorResolve = resolver(tokens.color.tokens);
for (const t of tokens.color.tokens) add(t.name, colorResolve(t.value));

for (const group of ["spacing", "radius", "canvas"]) {
  const list = tokens[group]?.tokens ?? [];
  const resolve = resolver(list);
  for (const t of list) add(t.name, resolve(t.value));
}

const families = tokens.type?.families ?? {};
for (const [name, value] of Object.entries(families)) add(`font-${name}`, value);

for (const g of tokens.type?.groups ?? []) {
  for (const s of g.styles ?? []) {
    add(`fs-${s.name}`, s.fontSize);
    if (s.fontWeight !== undefined) add(`fw-${s.name}`, s.fontWeight);
  }
}

const css =
  "/* Generated by scripts/tokens.mjs from pump/design/tokens.json. Do not edit. */\n" +
  `:root {\n${lines.join("\n")}\n}\n`;

mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, css);
console.log(`tokens.css: ${lines.length} variables`);
