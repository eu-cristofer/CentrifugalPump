"""Execute every worked use-case notebook (sprint 13).

Each ``use_cases/*.ipynb`` is run top to bottom in a fresh ``python3`` kernel; the
notebooks end with ``assert`` cells, so a regression in the library fails here.
The tests are marked ``slow`` (``pytest -m slow tests/test_notebooks.py``) but also
run in the default ``pytest``.  They are skipped cleanly when Jupyter
(``nbclient`` / ``ipykernel`` / ``nbformat``) is not installed.

The notebooks are generated by ``use_cases/build_notebooks.py``.
"""

from pathlib import Path

import pytest

nbformat = pytest.importorskip("nbformat")
nbclient = pytest.importorskip("nbclient")
pytest.importorskip("ipykernel")

USE_CASES = Path(__file__).resolve().parents[1] / "use_cases"
NOTEBOOKS = sorted(USE_CASES.glob("*.ipynb"))

EXPECTED = {
    "UC-00_utilities_demo",
    "UC-01_selection",
    "UC-02_performance_verification",
    "UC-03-04_system_operating_point",
    "UC-05_npsh",
    "UC-06_affinity_speed_change",
    "UC-07_trim",
    "UC-08_compare",
    "UC-09_reports",
    "UC-11_mechanical_run",
    "viscosity_HI967",
    "TR-01_witness_training",
}


def test_every_expected_notebook_exists():
    assert EXPECTED <= {p.stem for p in NOTEBOOKS}


@pytest.mark.slow
@pytest.mark.parametrize("path", NOTEBOOKS, ids=lambda p: p.stem)
def test_notebook_executes(path):
    nb = nbformat.read(path, as_version=4)
    client = nbclient.NotebookClient(
        nb,
        timeout=300,
        kernel_name="python3",
        resources={"metadata": {"path": str(path.parent)}},
    )
    client.execute()
